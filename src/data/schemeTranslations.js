/**
 * Returns a localized copy of a scheme object based on the requested language code.
 */
export function getLocalizedScheme(scheme, lang = 'en') {
  if (!scheme || lang === 'en') return scheme;
  const dict = schemeTranslations[lang]?.[scheme.id];
  if (!dict) return scheme;

  return {
    ...scheme,
    name: dict.name || scheme.name,
    shortDesc: dict.shortDesc || scheme.shortDesc,
    target: dict.target || scheme.target,
    eligibility: dict.eligibility || scheme.eligibility,
    benefits: dict.benefits || scheme.benefits,
    application_method: dict.application_method || scheme.application_method,
    implementing_agency: dict.implementing_agency || scheme.implementing_agency
  };
}

